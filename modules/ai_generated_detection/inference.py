"""Module 2 - AI-generated image detection (pluggable backend)."""

from __future__ import annotations

import time
from dataclasses import dataclass, field
from typing import Any

import numpy as np

from utils.image_utils import ensure_rgb_uint8

from .model import (
    AIDetectorUnavailable,
    BaseAIBackend,
    classify_probabilities,
    default_device,
    integration_status,
    load_backend,
)


@dataclass
class AIDetectionResult:
    status: str  # ok | unavailable | error
    predicted_class: str | None = None
    real_confidence: float | None = None
    ai_confidence: float | None = None
    uncertain: bool | None = None
    backend: str | None = None
    class_names: list[str] | None = None
    probabilities: list[float] | None = None
    image_size: tuple[int, int] | None = None
    elapsed_seconds: float = 0.0
    reason: str | None = None
    error_message: str | None = None
    warnings: list[str] = field(default_factory=list)
    limitations: list[str] = field(default_factory=list)
    backend_info: dict[str, Any] = field(default_factory=dict)

    def to_summary(self) -> dict:
        return {
            "status": self.status,
            "predicted_class": self.predicted_class,
            "real_confidence": self.real_confidence,
            "ai_confidence": self.ai_confidence,
            "uncertain": self.uncertain,
            "backend": self.backend,
            "class_names": self.class_names,
            "probabilities": self.probabilities,
            "image_size": list(self.image_size) if self.image_size else None,
            "elapsed_seconds": round(self.elapsed_seconds, 2),
            "reason": self.reason,
            "error": self.error_message,
            "warnings": list(self.warnings),
            "limitations": list(self.limitations),
            "backend_info": dict(self.backend_info),
        }


BASE_LIMITATIONS = [
    "AI-generated images and real photographs share low-level statistics; no detector is universally reliable.",
    "Accuracy depends on the training data of the supplied detector and on post-processing (resizing, compression).",
    "A prediction is evidence to review, not proof that an image was generated by AI.",
    "Images from generators not represented in the detector's training data may be misclassified.",
    "The 'uncertain' state is an honest abstention, not a hidden third class.",
]


def get_ai_status(manifest_path=None) -> dict:
    status = integration_status(manifest_path)
    return status.as_dict()


def _unavailable(reason: str, started: float, image_rgb: np.ndarray | None) -> AIDetectionResult:
    size = None
    if image_rgb is not None:
        size = (int(image_rgb.shape[1]), int(image_rgb.shape[0]))
    return AIDetectionResult(
        status="unavailable",
        reason=reason,
        image_size=size,
        elapsed_seconds=time.perf_counter() - started,
        warnings=[
            "No AI-generated-image detector is integrated, so no prediction is shown.",
            "This is a clearly marked integration placeholder, not a result from an untrained model.",
        ],
        limitations=BASE_LIMITATIONS,
    )


def detect_ai_generated_image(
    image_rgb: np.ndarray,
    *,
    backend: BaseAIBackend | None = None,
    manifest_path=None,
    device: str | None = None,
    uncertainty_margin: float | None = None,
    min_confidence: float | None = None,
) -> AIDetectionResult:
    """Classify an RGB image as real / AI-generated / uncertain.

    If ``backend`` is not supplied, the integration manifest at
    ``models/ai_detector/manifest.json`` is used.  When no usable detector is
    present the function returns ``status='unavailable'`` and never invents
    scores.
    """
    started = time.perf_counter()

    try:
        rgb = ensure_rgb_uint8(image_rgb)
    except Exception as exc:
        return AIDetectionResult(
            status="error",
            error_message=f"Invalid image: {exc}",
            warnings=["Module 2 could not read the uploaded image."],
            limitations=BASE_LIMITATIONS,
            elapsed_seconds=time.perf_counter() - started,
        )

    if backend is None:
        status = integration_status(manifest_path)
        if not status.available:
            return _unavailable(status.reason, started, rgb)
        try:
            backend = load_backend(manifest_path, device=device or default_device())
        except AIDetectorUnavailable as exc:
            return _unavailable(str(exc), started, rgb)
        except Exception as exc:  # pragma: no cover - defensive
            return AIDetectionResult(
                status="error",
                error_message=f"The AI detector could not be initialised: {exc}",
                image_size=(int(rgb.shape[1]), int(rgb.shape[0])),
                elapsed_seconds=time.perf_counter() - started,
                warnings=["Module 2 failed to start; other modules are unaffected."],
                limitations=BASE_LIMITATIONS,
            )

    manifest = getattr(backend, "manifest", {}) or {}
    try:
        probabilities = backend.predict(rgb)
        classification = classify_probabilities(
            probabilities,
            list(manifest.get("class_names", getattr(backend, "class_names", ["real", "ai_generated"]))),
            ai_class_index=manifest.get("ai_class_index"),
            uncertainty_margin=uncertainty_margin,
            min_confidence=min_confidence,
        )
    except Exception as exc:
        return AIDetectionResult(
            status="error",
            error_message=f"Inference failed: {exc}",
            image_size=(int(rgb.shape[1]), int(rgb.shape[0])),
            backend=getattr(backend, "name", None),
            elapsed_seconds=time.perf_counter() - started,
            warnings=["Module 2 inference failed; other modules are unaffected."],
            limitations=BASE_LIMITATIONS,
        )

    warnings = [
        "The displayed confidence comes from the integrated detector and is not a guarantee.",
        "Domain shift (resizing, screenshots, social-media compression) can reduce reliability.",
    ]
    if classification["uncertain"]:
        warnings.insert(
            0,
            "The detector abstained because the top confidence or class margin was too low.",
        )

    return AIDetectionResult(
        status="ok",
        predicted_class=classification["predicted_class"],
        real_confidence=classification["real_confidence"],
        ai_confidence=classification["ai_confidence"],
        uncertain=classification["uncertain"],
        backend=getattr(backend, "name", None),
        class_names=classification["class_names"],
        probabilities=classification["probabilities"],
        image_size=(int(rgb.shape[1]), int(rgb.shape[0])),
        elapsed_seconds=time.perf_counter() - started,
        warnings=warnings,
        limitations=BASE_LIMITATIONS,
        backend_info=backend.describe() if hasattr(backend, "describe") else {},
    )
